"""Matched planners on the existing 617 -> 614 -> 619 service route.

The independent unit is one complete mission, not each room or video frame.
The common task harness/global planner supplies pose references; compared
optimizers retain all supported motion families. No API calls are needed for
this motion-planning comparison. --limit changes scheduling only, not protocol.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import fcntl
import hashlib
import json
from pathlib import Path
import random
import subprocess
import sys
import threading

ROOT=Path(__file__).resolve().parents[1]


def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--seeds',type=int,nargs='+',default=[37,41,53,59,61])
    p.add_argument('--jobs',type=int,choices=(1,2),default=2)
    p.add_argument('--limit',type=int)
    a=p.parse_args();out=a.output.resolve();out.mkdir(parents=True,exist_ok=True)
    lock=(out/'campaign.lock').open('a');fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
    original=ROOT/'artifacts/hybrid_sequence_20261022/service_static_native_v3/long_task_plan.json'
    plan=json.loads(original.read_text())
    task=out/'task_plan.json'
    if task.exists():
        assert task.read_bytes()==original.read_bytes(),'Plan changed'
    else:task.write_bytes(original.read_bytes())
    files=list((ROOT/'src/rangermini_dynamic_semantic/rangermini_dynamic_semantic').glob('*.py'))
    files+=list((ROOT/'src/rangermini_dynamic_semantic/scripts').glob('*.py'))
    files+=[Path(__file__).resolve(),task,
        ROOT/'integration/nav2_mppi_adapter/bridge.cpp',
        ROOT/'integration/nav2_mppi_adapter/build/libranger_nav2_mppi.so',
        ROOT/'integration/mppi_native_core/core.cpp',
        ROOT/'integration/mppi_native_core/build/libranger_mppi_native.so']
    hashes={str(f.relative_to(ROOT)):digest(f)for f in files}
    methods=['nav2','hybrid','primitive','fixed']
    trials=[]
    for seed in a.seeds:
        order=methods[:] if seed==a.seeds[0] else random.Random(seed).sample(methods,len(methods))
        for method in order:
            trials.append(dict(seed=seed,method=method,name=f'route_{method}_s{seed}',domain=200+len(trials)))
    protocol=dict(independent_unit='complete 617 -> 614 -> 619 mission',
        task_plan_sha256=digest(task),instruction=plan['instruction'],seeds=a.seeds,methods=methods,
        intended_missions=len(trials),rooms=['617','614','619'],
        scene='multiroom_service_static; existing furnished world and service layout',
        common=['same registered service goals and acknowledgement rules',
                'same ObservedRouteGuide static-map global-planning code',
                'same finite-rate four-wheel execution model and stopping rules',
                'same map, lidar source, footprint and initial body/wheel state'],
        references='Generated by the common global planner from map and measured state; no manually drawn bypass',
        optimizer_config=dict(nav2='installed public Omni MPPI; lateral sampling retained; 1000 samples',
            primitive='no requested within-horizon transitions, 101-rollout cap',
            fixed='equal-duration phases, up to two transitions, 101-rollout cap',
            hybrid='searched phase boundaries, up to two transitions, 101-rollout cap'),
        prediction=dict(horizon=40,dt_s=.12,speed_bound_m_s=.35),
        limits=dict(sim_s=300,wall_s=900,requested_rtf=1.),
        qualification='World/source agreement and functioning external reference interface checked before interpretation; all attempts retained',
        statistical_scope='Room/exit/corridor segments are repeated observations within a mission, not independent samples',
        vlm='Archived common task plan, no fresh model calls; isolates motion planning',
        source_sha256=hashes,trials=trials)
    protocol_file=out/'protocol.json'
    if protocol_file.exists():assert json.loads(protocol_file.read_text())==protocol,'Frozen protocol/source changed'
    else:protocol_file.write_text(json.dumps(protocol,ensure_ascii=False,indent=2)+'\n')
    results=[];pending=[]
    for trial in trials:
        run=out/trial['name']
        if (run/'episode/result.json').exists():
            results.append(dict(trial,result=json.loads((run/'episode/result.json').read_text())))
        elif run.exists():raise RuntimeError(f'Partial attempt retained: {run}')
        else:pending.append(trial)
    if a.limit is not None:pending=pending[:a.limit]
    mutex=threading.Lock();running=set()
    def progress():
        (out/'progress.json').write_text(json.dumps(dict(running=sorted(running),complete=len(results),
            intended=len(trials),scheduled_this_invocation=len(pending)),indent=2)+'\n')
        (out/'results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2)+'\n')
    def execute(trial):
        assert all(digest(ROOT/k)==v for k,v in hashes.items()),'Source changed during batch'
        run=out/trial['name'];method=trial['method']
        cmd=[sys.executable,str(ROOT/'src/rangermini_dynamic_semantic/scripts/run_grounded_delivery.py'),
            '--output',str(run),'--planner','nav2-omni'if method=='nav2'else'ranger-mppi',
            '--long-task','--task-plan',str(task),'--service-confirmation','simulation',
            '--scenario','multiroom_service_static','--seed',str(trial['seed']),
            '--instruction',plan['instruction'],'--policy','predictive','--proposal-selector','cost',
            '--verified-recovery','--map-recovery','--stable-modes','--samples','6',
            '--upstream-samples','1000','--max-sim-time','300','--max-wall-time','900',
            '--real-time-factor','1','--ros-domain-id',str(trial['domain']),
            '--ign-partition','room_route_20261023_'+trial['name']]
        if method!='nav2':cmd+=['--hybrid-sequences','--hybrid-max-switches','0'if method=='primitive'else'2']
        if method=='fixed':cmd+=['--hybrid-fixed-timing']
        with mutex:running.add(trial['name']);progress()
        print('START',trial['name'],flush=True)
        with (out/f"{trial['name']}.log").open('w')as log:
            rc=subprocess.run(cmd,cwd=ROOT,stdout=log,stderr=subprocess.STDOUT).returncode
        terminal=run/'episode/result.json'
        result=json.loads(terminal.read_text())if terminal.exists()else dict(status='NO_TERMINAL_RECORD',task_success=False)
        row=dict(trial,return_code=rc,result=result)
        if terminal.exists():
            subprocess.run([sys.executable,str(ROOT/'tools/summarize_long_service_task.py'),str(run)],
                cwd=ROOT,stdout=subprocess.DEVNULL,check=True)
        with mutex:
            running.remove(trial['name']);results.append(row);progress()
        print('DONE',trial['name'],result['status'],flush=True)
        return row
    progress()
    with ThreadPoolExecutor(max_workers=a.jobs)as pool:
        futures=[pool.submit(execute,t)for t in pending]
        for future in as_completed(futures):future.result()
    print(f'FINISHED invocation; {len(results)}/{len(trials)} missions have terminal/attempt records',flush=True)


if __name__=='__main__':main()
